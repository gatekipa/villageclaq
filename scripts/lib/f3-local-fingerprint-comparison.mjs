export function reportLocalFingerprintQualificationFromQualify(qualify, options = {}) {
  const files = [];
  for (const step of Array.isArray(qualify?.sequence) ? qualify.sequence : []) {
    const file = step?.file;
    if (!file) continue;
    const captured = step.fingerprintAfterApply;
    const observed = captured?.fingerprint && typeof captured.fingerprint === "object"
      ? captured.fingerprint
      : (captured && typeof captured === "object" && captured.schema_version ? captured : null);
    let expected = null;
    try {
      expected = getFrozenExpectedFingerprint(file);
    } catch {
      expected = null;
    }
    if (!expected || !observed) continue;
    files.push({
      file,
      expected,
      observed,
      derived: false,
      notFreshPostgreSQLExecution: false,
    });
  }
  const reportOptions = {
    source: options.source || "live-qualify-sequence",
    derived: false,
    notFreshPostgreSQLExecution: false,
  };
  if (Object.prototype.hasOwnProperty.call(options, "platformAclEnvelopeDigest")) {
    reportOptions.platformAclEnvelopeDigest = options.platformAclEnvelopeDigest;
  }
  return reportLocalFingerprintQualification(files, reportOptions);
}
