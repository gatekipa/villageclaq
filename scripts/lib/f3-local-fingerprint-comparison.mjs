function sortKeysDeep(value) {
  if (Array.isArray(value)) return value.map((item) => sortKeysDeep(item));
  if (value && typeof value === "object") {
    const out = {};
    for (const key of Object.keys(value).sort()) out[key] = sortKeysDeep(value[key]);
    return out;
  }
  return value;
}

function stableJson(value) {
  return JSON.stringify(sortKeysDeep(value === undefined ? null : value));
}

function identityKey(record, fields) {
  return stableJson(fields.map((field) => record?.[field] ?? null));
}

function recordIdentityKey(record) {
  if (record == null || typeof record !== "object") return stableJson(record);
  const keys = Object.keys(record).sort();
  return stableJson(Object.fromEntries(keys.map((key) => [key, record[key]])));
}

function grantableOf(row) {
  if (row && Object.prototype.hasOwnProperty.call(row, "grantable")) return row.grantable;
  if (row && Object.prototype.hasOwnProperty.call(row, "is_grantable")) return row.is_grantable;
  return undefined;
}

function aclPairKey(row, parent, { ownerSelf = false } = {}) {
  const schema = row?.schema ?? parent?.schema ?? parent?.name ?? "";
  const objectName = row?.object_name ?? parent?.name ?? parent?.function ?? "";
  const grantee = ownerSelf && row?.grantee === LOCAL_ORACLE_CREATOR
    ? LOCAL_FIXTURE_CREATOR
    : row?.grantee;
  return stableJson([
    row?.object_type ?? parent?.object_type ?? parent?.relkind ?? "",
    schema,
    objectName,
    row?.prokind ?? "",
    row?.identity_arguments ?? parent?.identity_arguments ?? "",
    row?.privilege ?? null,
    grantableOf(row),
    grantee ?? null,
  ]);
}

function isRecognizedServiceRoleOmission(row, parent) {
  if (!row || row.grantee !== RECOGNIZED_OMISSION_RELATION.grantee) return false;
  if (grantableOf(row) !== false) return false;
  if (!RECOGNIZED_NON_GRANTABLE_SERVICE_ROLE_OMISSIONS.includes(row.privilege)) return false;
  const schema = row.schema ?? parent?.schema ?? null;
  const name = row.object_name ?? parent?.name ?? null;
  return schema === RECOGNIZED_OMISSION_RELATION.schema
    && name === RECOGNIZED_OMISSION_RELATION.name;
}

function allowCreatorRemap(expectedValue, observedValue, field) {
  if (expectedValue === observedValue) return { ok: true, remapped: false };
  const ownerSelfGrantee = field === "grantee";
  const allowedField = OWNER_REMAP_KEYS.includes(field) || ownerSelfGrantee;
  if (
    allowedField
    && expectedValue === LOCAL_ORACLE_CREATOR
    && observedValue === LOCAL_FIXTURE_CREATOR
  ) {
    return { ok: true, remapped: true };
  }
  return {
    ok: false,
    reason: `disallowed ${field} mapping expected=${expectedValue} observed=${observedValue}`,
  };
}

function fail(reason, extra = {}) {
  return { ok: false, reason, ...extra };
}

function compareExact(expected, observed, label) {
  if (stableJson(expected) === stableJson(observed)) return { ok: true };
  return fail(`${label} must match exactly`);
}

function pairByIdentity(expectedRows, observedRows, fields, label) {
  if (!Array.isArray(expectedRows) || !Array.isArray(observedRows)) {
    return fail(`${label} must be arrays for identity pairing`);
  }
  if (expectedRows.length !== observedRows.length) {
    return fail(
      `${label} identity count mismatch expected=${expectedRows.length} observed=${observedRows.length}`,
    );
  }
  const observedMap = new Map();
  for (const row of observedRows) {
    const key = identityKey(row, fields);
    if (observedMap.has(key)) return fail(`${label} duplicate observed identity ${key}`);
    observedMap.set(key, row);
  }
  const pairs = [];
  for (const expected of expectedRows) {
    const key = identityKey(expected, fields);
    const observed = observedMap.get(key);
    if (!observed) {
      return fail(`${label} identity missing or changed: ${key}`);
    }
    observedMap.delete(key);
    pairs.push({ expected, observed });
  }
  if (observedMap.size > 0) {
    return fail(`${label} extra observed identities`, {
      extra: [...observedMap.keys()],
    });
  }
  return { ok: true, pairs };
}

function compareAclSets(expectedRows, observedRows, parent, envelopeOk) {
  const expected = Array.isArray(expectedRows) ? [...expectedRows] : [];
  const observed = Array.isArray(observedRows) ? [...observedRows] : [];
  const usedObserved = new Set();
  const recognizedOmissions = [];

  const takeObserved = (predicate) => {
    const index = observed.findIndex((row, i) => !usedObserved.has(i) && predicate(row));
    if (index < 0) return null;
    usedObserved.add(index);
    return observed[index];
  };

  for (const exp of expected) {
    const exact = takeObserved((row) => aclPairKey(row, parent) === aclPairKey(exp, parent));
    const remapped = exact
      ? null
      : takeObserved((row) => (
        exp.grantee === LOCAL_ORACLE_CREATOR
        && row.grantee === LOCAL_FIXTURE_CREATOR
        && aclPairKey(row, parent, { ownerSelf: true }) === aclPairKey(exp, parent, { ownerSelf: true })
      ));
    const matched = exact || remapped;
    if (!matched) {
      if (envelopeOk && isRecognizedServiceRoleOmission(exp, parent)) {
        recognizedOmissions.push({
          schema: RECOGNIZED_OMISSION_RELATION.schema,
          object_name: RECOGNIZED_OMISSION_RELATION.name,
          grantee: exp.grantee,
          privilege: exp.privilege,
          grantable: grantableOf(exp),
        });
        continue;
      }
      if (isRecognizedServiceRoleOmission(exp, parent) && !envelopeOk) {
        return fail(
          "recognized service_role omission requires sealed platform-envelope digest "
          + SEALED_PLATFORM_ACL_ENVELOPE_DIGEST,
        );
      }
      return fail(
        `ACL identity or privilege missing for ${exp.schema || parent?.schema || ""}.`
        + `${exp.object_name || parent?.name || ""} ${exp.grantee} ${exp.privilege}`,
      );
    }
    if (grantableOf(exp) !== grantableOf(matched)) {
      return fail("privilege grant-option changed");
    }
    if (exp.privilege !== matched.privilege) {
      return fail("privilege type changed");
    }
    const granteeOk = exact
      ? compareExact(exp.grantee, matched.grantee, "ACL grantee")
      : allowCreatorRemap(exp.grantee, matched.grantee, "grantee");
    if (!granteeOk.ok) {
      return fail(granteeOk.reason || "ACL grantee mapping rejected");
    }
    const grantorOk = allowCreatorRemap(exp.grantor, matched.grantor, "grantor");
    if (!grantorOk.ok) return fail(grantorOk.reason);
    const restExpected = { ...exp };
    const restObserved = { ...matched };
    delete restExpected.grantee;
    delete restExpected.grantor;
    delete restObserved.grantee;
    delete restObserved.grantor;
    const rest = compareExact(restExpected, restObserved, "ACL remainder after creator remap");
    if (!rest.ok) return rest;
  }

  const extra = observed.filter((_, i) => !usedObserved.has(i));
  if (extra.length > 0) {
    return fail("additional observed ACL tuples are outside the local profile", {
      extraCount: extra.length,
    });
  }
  return { ok: true, recognizedOmissions };
}

function compareRecord(expected, observed, collection, envelopeOk) {
  if (expected == null || observed == null || typeof expected !== "object" || typeof observed !== "object") {
    return compareExact(expected, observed, collection);
  }
  const keys = [...new Set([...Object.keys(expected), ...Object.keys(observed)])].sort();
  const recognizedOmissions = [];
  for (const key of keys) {
    const ev = expected[key];
    const ov = observed[key];
    if (OWNER_REMAP_KEYS.includes(key)) {
      const remap = allowCreatorRemap(ev, ov, key);
      if (!remap.ok) return fail(`${collection}.${key}: ${remap.reason}`);
      continue;
    }
    if (key === "grantee") {
      const remap = allowCreatorRemap(ev, ov, "grantee");
      if (!remap.ok) return fail(`${collection}.grantee: ${remap.reason}`);
      continue;
    }
    if (ACL_COLLECTION_KEYS.includes(key)) {
      const acl = compareAclSets(ev, ov, expected, envelopeOk);
      if (!acl.ok) return fail(`${collection}.${key}: ${acl.reason}`);
      recognizedOmissions.push(...(acl.recognizedOmissions || []));
      continue;
    }
    if (EXACT_SECURITY_KEYS.includes(key) || key === "identity_arguments") {
      const exact = compareExact(ev, ov, `${collection}.${key}`);
      if (!exact.ok) return exact;
      continue;
    }
    if (Array.isArray(ev) || Array.isArray(ov)) {
      if (LOCAL_IDENTITY_KEYS[key]) {
        const nested = compareCollection(ev, ov, key, envelopeOk);
        if (!nested.ok) return nested;
        recognizedOmissions.push(...(nested.recognizedOmissions || []));
        continue;
      }
      const exact = compareExact(ev, ov, `${collection}.${key}`);
      if (!exact.ok) return exact;
      continue;
    }
    if (ev && ov && typeof ev === "object" && typeof ov === "object") {
      const nested = compareRecord(ev, ov, `${collection}.${key}`, envelopeOk);
      if (!nested.ok) return nested;
      recognizedOmissions.push(...(nested.recognizedOmissions || []));
      continue;
    }
    const exact = compareExact(ev, ov, `${collection}.${key}`);
    if (!exact.ok) return exact;
  }
  return { ok: true, recognizedOmissions };
}

function compareCollection(expectedRows, observedRows, collection, envelopeOk) {
  const fields = LOCAL_IDENTITY_KEYS[collection];
  if (!fields) return compareExact(expectedRows, observedRows, collection);
  const paired = pairByIdentity(expectedRows || [], observedRows || [], fields, collection);
  if (!paired.ok) return paired;
  const recognizedOmissions = [];
  for (const { expected, observed } of paired.pairs) {
    const compared = compareRecord(expected, observed, collection, envelopeOk);
    if (!compared.ok) return compared;
    recognizedOmissions.push(...(compared.recognizedOmissions || []));
  }
  return { ok: true, recognizedOmissions };
}

function compareObjectAllowingOwner(expected, observed, label, envelopeOk) {
  if (expected == null && observed == null) return { ok: true, recognizedOmissions: [] };
  if (expected == null || observed == null || typeof expected !== "object" || typeof observed !== "object") {
    return compareExact(expected, observed, label);
  }
  return compareRecord(expected, observed, label, envelopeOk);
}

export function evaluateEnvelopeIdentity(envelopeDigest) {
  if (envelopeDigest == null || envelopeDigest === "") {
    return fail("missing sealed platform-envelope digest");
  }
  if (envelopeDigest !== SEALED_PLATFORM_ACL_ENVELOPE_DIGEST) {
    return fail(
      `incorrect platform-envelope digest actual=${envelopeDigest} sealed=${SEALED_PLATFORM_ACL_ENVELOPE_DIGEST}`,
    );
  }
  return {
    ok: true,
    digest: SEALED_PLATFORM_ACL_ENVELOPE_DIGEST,
    boundException: "seven non-grantable service_role omissions on public.financial_ledger_epochs",
  };
}

export function compareLocalFingerprint(expected, observed, options = {}) {
  const file = options.file || expected?.migration_file || observed?.migration_file || null;
  const raw = fingerprintCompleteAndExact({ expected, observed }, file);
  const envelope = evaluateEnvelopeIdentity(options.platformAclEnvelopeDigest);
  const recognizedOmissions = [];

  const reject = (reason) => ({
    profile: LOCAL_FINGERPRINT_COMPARISON_PROFILE_V1,
    ok: false,
    accepted: false,
    reason,
    rawEquality: raw.ok === true,
    rawReason: raw.reason || null,
    rawCode: raw.ok === true ? null : F23_FINGERPRINT_MISMATCH,
    envelope,
    recognizedOmissions,
    repairAuthorized: false,
    hostedEquality: false,
    localCatalogComparisonOnly: true,
  });

  if (!envelope.ok) return reject(envelope.reason);
  if (!expected || !observed || typeof expected !== "object" || typeof observed !== "object") {
    return reject("expected and observed fingerprints are required");
  }

  const expectedCanon = canonicalizeFingerprintForCompare(structuredClone(expected));
  const observedCanon = canonicalizeFingerprintForCompare(structuredClone(observed));
  const keys = [...new Set([...Object.keys(expectedCanon), ...Object.keys(observedCanon)])].sort();
  for (const key of keys) {
    if (!Object.prototype.hasOwnProperty.call(expectedCanon, key)) {
      return reject(`expected missing key ${key}`);
    }
    if (!Object.prototype.hasOwnProperty.call(observedCanon, key)) {
      return reject(`observed missing key ${key}`);
    }
    const ev = expectedCanon[key];
    const ov = observedCanon[key];
    if (LOCAL_EXACT_COLLECTIONS.includes(key)) {
      const exact = compareExact(ev, ov, key);
      if (!exact.ok) return reject(`${key} must match exactly`);
      continue;
    }
    if (COLLECTION_KEYS.includes(key) && (Array.isArray(ev) || Array.isArray(ov))) {
      const compared = compareCollection(ev, ov, key, true);
      if (!compared.ok) return reject(compared.reason);
      recognizedOmissions.push(...(compared.recognizedOmissions || []));
      continue;
    }
    if (ACL_COLLECTION_KEYS.includes(key)) {
      const compared = compareAclSets(ev, ov, null, true);
      if (!compared.ok) return reject(compared.reason);
      recognizedOmissions.push(...(compared.recognizedOmissions || []));
      continue;
    }
    if (key === "hgp" || key === "enqueue" || key === "hgp_pin" || key === "owner") {
      const compared = compareObjectAllowingOwner(ev, ov, key, true);
      if (!compared.ok) return reject(compared.reason);
      continue;
    }
    const exact = compareExact(ev, ov, key);
    if (!exact.ok) return reject(exact.reason);
  }

  return {
    profile: LOCAL_FINGERPRINT_COMPARISON_PROFILE_V1,
    ok: true,
    accepted: true,
    reason: null,
    rawEquality: raw.ok === true,
    rawReason: raw.reason || null,
    rawCode: raw.ok === true ? null : F23_FINGERPRINT_MISMATCH,
    envelope,
    recognizedOmissions,
    repairAuthorized: false,
    hostedEquality: false,
    localCatalogComparisonOnly: true,
    doesNotEstablishRoleEquivalence: true,
    doesNotEstablishRestrictedRoleEnforcement: true,
    doesNotEstablishHostedAuthorization: true,
  };
}

export function reconstructDerivedObservedFingerprint(expected, diffs) {
  const left = canonicalizeFingerprintForCompare(expected);
  const observed = structuredClone(left);
  for (const diff of diffs || []) {
    if (diff.kind === "record_set") {
      const expectedRows = Array.isArray(left[diff.field]) ? left[diff.field] : [];
      const expectedMap = new Map(expectedRows.map((row) => [recordIdentityKey(row), row]));
      for (const row of diff.onlyInExpected || []) {
        expectedMap.delete(recordIdentityKey(row));
      }
      observed[diff.field] = [...expectedMap.values(), ...(diff.onlyInObserved || [])];
    } else if (diff.kind === "value") {
      observed[diff.field] = structuredClone(diff.observed);
    }
  }
  return {
    fingerprint: observed,
    derived: true,
    notFreshPostgreSQLExecution: true,
  };
}

